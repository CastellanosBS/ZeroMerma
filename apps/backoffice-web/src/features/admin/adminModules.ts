export const adminModuleByKey = new Map<AdminModuleKey, AdminModuleDefinition>(
  adminModules.map((module) => [module.key, module]),
);

export function getAdminModule(moduleKey: AdminModuleKey): AdminModuleDefinition {
  const module = adminModuleByKey.get(moduleKey);
  if (!module) {
    throw new Error(`Unknown admin module: ${moduleKey}`);
  }

  return module;
}

export function getAdminModulesBySection(sectionKey: AdminSectionKey): AdminModuleDefinition[] {
  return adminModules.filter((module) => module.sectionKey === sectionKey);
}

