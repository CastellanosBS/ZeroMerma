function columns(labels: string[]): AdminTableColumn[] {
  return labels.map((label) => ({
    key: label
      .normalize("NFD")
      .replace(/[\u0300-\u036f]/g, "")
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/(^-|-$)/g, ""),
    label,
  }));
}

function moduleDefinition(
  definition: Omit<AdminModuleDefinition, "path"> & { routeSlug: string },
): AdminModuleDefinition {
  return {
    ...definition,
    path: `/admin/${definition.routeSlug}`,
  };
}

