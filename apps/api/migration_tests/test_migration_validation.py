def _load_model_metadata() -> None:
    for module in MODEL_MODULES:
        import_module(module)


def _normalize_sql(value: object) -> str:
    return re.sub(r"\s+", " ", str(value).strip())


def _schema_name(value: object) -> str:
    return str(value) if value else "public"


def _expression_fingerprint(value: object) -> str:
    name = getattr(value, "name", None)
    table = getattr(value, "table", None)
    if name is not None and table is not None:
        return f"column:{name}"
    return f"expression:{_normalize_sql(value)}"


def _index_predicate(index: sa.Index) -> str | None:
    predicate = index.dialect_options["postgresql"].get("where")
    return _normalize_sql(predicate) if predicate is not None else None


def _index_fingerprint_from_alembic(index: sa.Index) -> IndexFingerprint:
    table = index.table
    if table is None or index.name is None:
        raise AssertionError("Alembic index drift lacks a stable table/name identity.")
    return IndexFingerprint(
        schema=_schema_name(table.schema),
        table=table.name,
        index_name=str(index.name),
        unique=bool(index.unique),
        expressions=tuple(_expression_fingerprint(item) for item in index.expressions),
        predicate=_index_predicate(index),
    )


def _index_fingerprint_from_inspector(
    table_name: str,
    item: Mapping[str, object],
) -> IndexFingerprint:
    name = item.get("name")
    if name is None:
        raise AssertionError(f"{table_name}: reflected index has no name")
    column_names = tuple(cast(list[str | None], item.get("column_names") or []))
    raw_expressions = tuple(cast(list[object], item.get("expressions") or []))
    expressions: list[str] = []
    for ordinal, column_name in enumerate(column_names):
        if column_name is not None:
            expressions.append(f"column:{column_name}")
        elif ordinal < len(raw_expressions):
            expressions.append(f"expression:{_normalize_sql(raw_expressions[ordinal])}")
        else:
            expressions.append("expression:<missing>")
    dialect_options = cast(Mapping[str, object], item.get("dialect_options") or {})
    predicate = dialect_options.get("postgresql_where")
    return IndexFingerprint(
        schema="public",
        table=table_name,
        index_name=str(name),
        unique=bool(item.get("unique")),
        expressions=tuple(expressions),
        predicate=_normalize_sql(predicate) if predicate is not None else None,
    )


def _server_default_fingerprint(diff: tuple[object, ...]) -> ServerDefaultFingerprint:
    if len(diff) < 6 or str(diff[0]) != "modify_default":
        raise AssertionError(f"Invalid server-default diff shape: {diff!r}")
    database_default = getattr(diff[-2], "arg", diff[-2])
    metadata_default = diff[-1]
    return ServerDefaultFingerprint(
        schema=_schema_name(diff[1]),
        table=str(diff[2]),
        column=str(diff[3]),
        database_default=_normalize_sql(database_default),
        expected_metadata_default_state=("ABSENT" if metadata_default is None else "PRESENT"),
    )


def _check_fingerprint(
    table_name: str,
    item: Mapping[str, object],
) -> CheckConstraintFingerprint:
    name = item.get("name")
    if name is None:
        raise AssertionError(f"{table_name}: reflected check constraint has no name")
    return CheckConstraintFingerprint(
        schema="public",
        table=table_name,
        constraint_name=str(name),
        expression=_normalize_sql(item.get("sqltext") or ""),
    )


def _model_check_fingerprint(
    table_name: str,
    constraint: sa.CheckConstraint,
    expected_database_name: str,
    actual: CheckConstraintFingerprint,
) -> ModelCheckFingerprint:
    if constraint.name is None:
        raise AssertionError(f"{table_name}: model check constraint has no name")
    return ModelCheckFingerprint(
        schema="public",
        table=table_name,
        model_name=str(constraint.name),
        expected_database_name=expected_database_name,
        database_name=actual.constraint_name,
        model_expression=_normalize_sql(constraint.sqltext),
        database_expression=actual.expression,
    )


def _classify_exact(
    fingerprint: object,
    known_fingerprints: Collection[object],
    known_classification: str,
) -> str:
    if fingerprint in known_fingerprints:
        return known_classification
    return UNKNOWN_SCHEMA_DRIFT


def _classify_model_check(
    fingerprint: ModelCheckFingerprint,
    known_fingerprints: Collection[object] = KNOWN_MODEL_CHECKS,
) -> str:
    if fingerprint not in known_fingerprints:
        return UNKNOWN_SCHEMA_DRIFT
    if fingerprint.expected_database_name != fingerprint.database_name:
        return KNOWN_NAMING_ONLY
    return KNOWN_MODEL_OBJECT


def _fingerprint_record(fingerprint: object) -> dict[str, object]:
    if isinstance(
        fingerprint,
        (
            IndexFingerprint,
            ServerDefaultFingerprint,
            CheckConstraintFingerprint,
            ModelCheckFingerprint,
        ),
    ):
        return cast(dict[str, object], asdict(fingerprint))
    return {"identity": repr(fingerprint)}


def _unknown_drift_message(records: list[dict[str, object]]) -> str:
    return f"{UNKNOWN_SCHEMA_DRIFT}: {json.dumps(records, sort_keys=True, default=str)}"


