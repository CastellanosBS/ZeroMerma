def _assignment_value(tree: ast.Module, name: str) -> object:
    for node in tree.body:
        target: ast.expr
        value: ast.expr | None
        if isinstance(node, ast.Assign):
            target = node.targets[0]
            value = node.value
        elif isinstance(node, ast.AnnAssign):
            target = node.target
            value = node.value
        else:
            continue
        if isinstance(target, ast.Name) and target.id == name and value is not None:
            return ast.literal_eval(value)
    return None


def _called_functions(
    function: ast.FunctionDef, local_functions: Mapping[str, ast.FunctionDef]
) -> list[ast.FunctionDef]:
    result = [function]
    seen = {function.name}
    pending = [function]
    while pending:
        current = pending.pop()
        for node in ast.walk(current):
            if not isinstance(node, ast.Call) or not isinstance(node.func, ast.Name):
                continue
            called = local_functions.get(node.func.id)
            if called is not None and called.name not in seen:
                seen.add(called.name)
                result.append(called)
                pending.append(called)
    return result


def _operation_summary(tree: ast.Module, function_name: str) -> tuple[dict[str, int], list[str]]:
    local_functions = {node.name: node for node in tree.body if isinstance(node, ast.FunctionDef)}
    root = local_functions[function_name]
    operation_names: list[str] = []
    sql_fragments: list[str] = []
    for function in _called_functions(root, local_functions):
        for node in ast.walk(function):
            if not isinstance(node, ast.Call):
                continue
            rendered_name = ""
            if (
                isinstance(node.func, ast.Attribute)
                and isinstance(node.func.value, ast.Name)
                and node.func.value.id == "op"
            ):
                rendered_name = f"op.{node.func.attr}"
            elif isinstance(node.func, ast.Attribute) and node.func.attr == "execute":
                rendered_name = "connection.execute"
            if not rendered_name:
                continue
            operation_names.append(rendered_name)
            if rendered_name.endswith("execute") and node.args:
                sql_fragments.append(ast.unparse(node.args[0]))
    counts = {name: operation_names.count(name) for name in sorted(set(operation_names))}
    return counts, sql_fragments


def _revision_inventory() -> list[dict[str, object]]:
    inventory: list[dict[str, object]] = []
    for path in sorted(VERSIONS_DIR.glob("*.py")):
        source = path.read_text(encoding="utf-8-sig")
        tree = ast.parse(source, filename=str(path))
        upgrade_operations, upgrade_sql = _operation_summary(tree, "upgrade")
        downgrade_operations, downgrade_sql = _operation_summary(tree, "downgrade")
        rendered_upgrade = "\n".join(upgrade_sql).upper()
        data_migration = bool(
            re.search(r"\b(INSERT|UPDATE|DELETE)\b", rendered_upgrade)
            or upgrade_operations.get("op.bulk_insert")
        )
        potentially_destructive = bool(
            re.search(r"\b(DELETE|DROP|TRUNCATE)\b", rendered_upgrade)
            or any(
                upgrade_operations.get(name)
                for name in (
                    "op.drop_column",
                    "op.drop_constraint",
                    "op.drop_table",
                    "op.alter_column",
                )
            )
        )
        existing_data_assumption = bool(
            data_migration
            or any(
                upgrade_operations.get(name)
                for name in (
                    "op.add_column",
                    "op.alter_column",
                    "op.create_unique_constraint",
                    "op.drop_column",
                    "op.drop_constraint",
                )
            )
        )
        if potentially_destructive or data_migration:
            lock_risk = "HIGH_LOCK_RISK"
        elif any(
            upgrade_operations.get(name)
            for name in ("op.add_column", "op.create_index", "op.create_unique_constraint")
        ):
            lock_risk = "MEDIUM_LOCK_RISK"
        else:
            lock_risk = "LOW_LOCK_RISK"
        if any(
            downgrade_operations.get(name) for name in ("op.drop_table", "op.drop_column")
        ) or re.search(r"\bDELETE\b", "\n".join(downgrade_sql).upper()):
            downgrade_classification = "LOSSY"
        elif data_migration:
            downgrade_classification = "NOT_MEANINGFUL"
        elif downgrade_operations.get("op.drop_constraint"):
            downgrade_classification = "UNSAFE"
        else:
            downgrade_classification = "SAFE_STRUCTURAL_REVERSAL"
        inventory.append(
            {
                "ordinal": len(inventory) + 1,
                "filename": path.name,
                "revision": _assignment_value(tree, "revision"),
                "down_revision": _assignment_value(tree, "down_revision"),
                "branch_labels": _assignment_value(tree, "branch_labels"),
                "depends_on": _assignment_value(tree, "depends_on"),
                "upgrade_operations": upgrade_operations,
                "downgrade_operations": downgrade_operations,
                "data_migration": data_migration,
                "potentially_destructive": potentially_destructive,
                "requires_existing_data_assumption": existing_data_assumption,
                "transactional_risk": "DATA_AND_DDL" if data_migration else "DDL",
                "lock_risk": lock_risk,
                "downgrade_classification": downgrade_classification,
            }
        )
    return inventory


def _graph(inventory: list[dict[str, object]]) -> dict[str, object]:
    revisions = [str(row["revision"]) for row in inventory]
    revision_set = set(revisions)
    parents = {str(row["revision"]): row["down_revision"] for row in inventory}
    children: dict[str, list[str]] = {revision: [] for revision in revisions}
    unresolved: list[tuple[str, str]] = []
    for revision, down_revision in parents.items():
        parent_revisions: tuple[object, ...]
        if down_revision is None:
            parent_revisions = ()
        elif isinstance(down_revision, tuple):
            parent_revisions = down_revision
        else:
            parent_revisions = (down_revision,)
        for parent in parent_revisions:
            rendered_parent = str(parent)
            if rendered_parent not in revision_set:
                unresolved.append((revision, rendered_parent))
            else:
                children[rendered_parent].append(revision)
    roots = [revision for revision, parent in parents.items() if parent is None]
    heads = [revision for revision, descendants in children.items() if not descendants]
    visited: set[str] = set()
    active: set[str] = set()
    cycles: list[list[str]] = []

    def visit(revision: str, path: list[str]) -> None:
        if revision in active:
            cycles.append(path[path.index(revision) :] + [revision])
            return
        if revision in visited:
            return
        active.add(revision)
        for child in children[revision]:
            visit(child, [*path, child])
        active.remove(revision)
        visited.add(revision)

    for root in roots:
        visit(root, [root])
    return {
        "revision_count": len(revisions),
        "unique_revision_count": len(revision_set),
        "duplicate_revisions": sorted(
            {revision for revision in revisions if revisions.count(revision) > 1}
        ),
        "roots": roots,
        "heads": heads,
        "unresolved_down_revisions": unresolved,
        "cycles": cycles,
        "unreachable": sorted(revision_set - visited),
        "branches": {
            revision: descendants
            for revision, descendants in children.items()
            if len(descendants) > 1
        },
        "merge_revisions": [
            revision for revision, parent in parents.items() if isinstance(parent, tuple)
        ],
    }


def _topological_revisions(inventory: list[dict[str, object]]) -> list[str]:
    by_parent = {row["down_revision"]: str(row["revision"]) for row in inventory}
    revisions: list[str] = []
    current: object = None
    while current in by_parent:
        revision = by_parent[current]
        revisions.append(revision)
        current = revision
    return revisions


