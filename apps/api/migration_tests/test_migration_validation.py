@contextmanager
def _temporary_database(
    root_engine: Engine,
    root_config: DestructiveTestDatabaseConfig,
    label: str,
) -> Iterator[tuple[DestructiveTestDatabaseConfig, Engine]]:
    child_config = _child_config(root_config, label)
    if not re.fullmatch(r"[a-z0-9_]+", child_config.database):
        raise AssertionError("Generated test database identifier is not safe.")
    with _guarded_admin_connection(root_engine, root_config) as admin_connection:
        admin_connection.exec_driver_sql(f'CREATE DATABASE "{child_config.database}"')
    child_engine = _build_engine(child_config)
    try:
        with child_engine.connect() as connection:
            assert_authorized_destructive_connection(connection, child_config)
        yield child_config, child_engine
    finally:
        child_engine.dispose()
        with _guarded_admin_connection(root_engine, root_config) as admin_connection:
            admin_connection.execute(
                text(
                    "SELECT pg_terminate_backend(pid) FROM pg_stat_activity "
                    "WHERE datname = :database AND pid <> pg_backend_pid()"
                ),
                {"database": child_config.database},
            )
            admin_connection.exec_driver_sql(f'DROP DATABASE IF EXISTS "{child_config.database}"')


